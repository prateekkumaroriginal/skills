// Bundle assets/icons/*.svg (Lucide, ISC) into src/icons.js as inner-SVG strings keyed by name.
import fs from 'node:fs'; import path from 'node:path'; import { fileURLToPath } from 'node:url';
const HERE = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(HERE, '..', 'assets', 'icons');
const out = {};
for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.svg'))) {
  const s = fs.readFileSync(path.join(dir, f), 'utf8');
  out[f.replace('.svg', '')] = s.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>[\s\S]*$/, '').replace(/<!--[\s\S]*?-->/g, '').trim();
}
fs.writeFileSync(path.join(HERE, 'icons.js'), '// generated by build_icons.mjs from assets/icons (Lucide, ISC license)\nconst ICONS = ' + JSON.stringify(out, null, 1) + ';\n');
console.log(Object.keys(out).length, 'icons');
